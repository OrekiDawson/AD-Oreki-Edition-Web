function replaceOnce(haystack, needle, next, label) {
  const first = haystack.indexOf(needle);
  if (first < 0) throw new Error(`${label}：找不到片段`);
  if (haystack.indexOf(needle, first + 1) >= 0) throw new Error(`${label}：片段出现多次`);
  return haystack.slice(0, first) + next + haystack.slice(first + needle.length);
}

